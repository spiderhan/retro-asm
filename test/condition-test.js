'use strict';
const assert = require('assert');
const { parseCondition, parseHits } = require('../lib/condition');
const syms = new Map([['SCORE', 0x8310], ['LOOP', 0xA00E]]);
const regs = { R0: 5, R1: 3, R2: 0x1F, PC: 0xA00E, WP: 0x8300, ST: 0 };
const mem = { 0x8310: 12 };
const ctx = { regs, word: async (a) => mem[a] || 0 };
const t = async (s) => parseCondition(s, syms).test(ctx);
(async () => {
  assert.strictEqual(await t('R0 = 5'), true);
  assert.strictEqual(await t('R0 == 6'), false);
  assert.strictEqual(await t('R0 <> 6'), true);
  assert.strictEqual(await t('R2 = >1F'), true);
  assert.strictEqual(await t('R2>=>1F'), true, 'no spaces, hex on the right');
  assert.strictEqual(await t('R2 > >1E'), true);
  assert.strictEqual(await t('R2 = 0x1f'), true);
  assert.strictEqual(await t('R0 < R2'), true);
  assert.strictEqual(await t('PC = LOOP'), true, 'a label is its address');
  assert.strictEqual(await t('@SCORE > 9'), true, '@ reads the word stored there');
  assert.strictEqual(await t('@>8310 = 12'), true);
  assert.strictEqual(await t('R1 & 1'), true, '& tests bits');
  assert.strictEqual(await t('R1 & 4'), false);
  assert.strictEqual(await t('R0'), true, 'a lone value means "not zero"');
  assert.strictEqual(await t('R0 = 5 and R1 = 3'), true);
  assert.strictEqual(await t('R0 = 5 && R1 = 4'), false);
  assert.strictEqual(await t('R0 = 9 or R1 = 3'), true);
  assert.strictEqual(await t('R0 = 9 || R1 = 4'), false);
  assert.strictEqual(await t('r0 = 5'), true, 'capitals do not matter');
  for (const bad of ['R99 = 1', 'FOO = 1', 'R0 =', '= 5']) assert.throws(() => parseCondition(bad, syms), Error, bad);
  assert.ok(/not a register/.test((() => { try { parseCondition('FOO = 1', syms); } catch (e) { return e.message; } })()));
  const h = parseHits('3'); assert.deepStrictEqual([1, 2, 3, 4].map(h), [false, false, true, false]);
  assert.deepStrictEqual([1, 2, 3].map(parseHits('>=2')), [false, true, true]);
  assert.deepStrictEqual([1, 2, 3, 4].map(parseHits('%2')), [false, true, false, true]);
  assert.throws(() => parseHits('often'));
  console.log('condition-test: all good');
})().catch(e => { console.log('FAIL', e.stack || e); process.exit(1); });
